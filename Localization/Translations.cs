        {
            return new Dictionary<string, string>
            {
                { s.GetSettingsLocaleID(), ModName },

                // Les réglages de géométrie/organique (Mode, Colonnes, Lignes, Espacement,
                // Angle, Beco sem saída, Variação orgânica, etc.) n'ont plus de page dans
                // Options > Mods (SettingsUIHidden côté GridRoadGeneratorSettings) : ils ne
                // se pilotent plus que depuis le panneau en jeu. Leurs libellés (t.ModeLabel,
                // t.ColumnsLabel, ...) restent utilisés plus bas pour les clés
                // "GridRoadGenerator.UI.*" lues par ce panneau — seules les entrées
                // Options.GROUP/OPTION/OPTION_DESCRIPTION propres à la page Options ont été
                // retirées ici.

                { s.GetOptionGroupLocaleID(GridRoadGeneratorSettings.GroupGeneral), t.GroupGeneral },
                { s.GetOptionLabelLocaleID(nameof(GridRoadGeneratorSettings.AutoResolveCollisions)), t.AutoResolveCollisionsLabel },
                { s.GetOptionDescLocaleID(nameof(GridRoadGeneratorSettings.AutoResolveCollisions)), t.AutoResolveCollisionsDesc },
                { s.GetOptionGroupLocaleID(GridRoadGeneratorSettings.GroupKeybindings), t.GroupKeybindings },

                // Lignes du menu Options (une par propriété ProxyBinding).
                { s.GetOptionLabelLocaleID(nameof(GridRoadGeneratorSettings.ToggleToolBinding)), t.ToggleToolLabel },
                { s.GetOptionDescLocaleID(nameof(GridRoadGeneratorSettings.ToggleToolBinding)), t.ToggleToolDesc },
                { s.GetOptionLabelLocaleID(nameof(GridRoadGeneratorSettings.ConfirmGridBinding)), t.ConfirmGridLabel },
                { s.GetOptionDescLocaleID(nameof(GridRoadGeneratorSettings.ConfirmGridBinding)), t.ConfirmGridDesc },

